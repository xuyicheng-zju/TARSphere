#!/usr/bin/env bash
# Mirror the Isaac Sim runtime roots onto local disk.
#
# Kit resolves MDL materials through many small file accesses. Network
# filesystem latency can dominate scene loading; staging the runtime and
# assets locally avoids repeated remote metadata requests.
#
# Idempotent: files matching on size and mtime are skipped, so re-running after
# an interrupted copy resumes rather than restarts.
#
# Usage:
#   scripts/stage.sh [--scratch DIR] [--dry-run] [--yes]
#                                  [--workers N]
#
# Requires ISAAC_SIM_PATH / TARSPHERE_ASSETS_PATH to be set,
# i.e. run it in the same shell where you would source scripts/activate.sh.
# Prints the export lines to add to your host environment file when done.

set -euo pipefail

SCRATCH="${TARSPHERE_LOCAL_SCRATCH:-/tmp/$(id -un)_tarsphere_runtime}"
DRY_RUN=0
ASSUME_YES=0
WORKERS=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --scratch)
      SCRATCH="${2:?--scratch needs a directory}"
      shift 2
      ;;
    --workers)
      WORKERS="${2:?--workers needs a count}"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --yes | -y)
      ASSUME_YES=1
      shift
      ;;
    -h | --help)
      sed -n '2,24p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 2
      ;;
  esac
done

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

: "${ISAAC_SIM_PATH:?Set ISAAC_SIM_PATH before staging.}"
: "${TARSPHERE_ASSETS_PATH:=$REPO_ROOT/assets}"
export TARSPHERE_ASSETS_PATH

PYTHON_BIN="${PYTHON_BIN:-python3}"
command -v "$PYTHON_BIN" >/dev/null || PYTHON_BIN=python

echo "== current runtime roots =="
"$PYTHON_BIN" -m tarsphere.infra.simulation.local_stage || true
echo

PLAN="$("$PYTHON_BIN" -m tarsphere.infra.simulation.local_stage --plan "$SCRATCH")"
STAGE_LINES="$(printf '%s\n' "$PLAN" | awk -F'\t' '$1 == "STAGE"')"

if [[ -z "$STAGE_LINES" ]]; then
  echo "All runtime roots are already on local disk; only caches need pinning."
else
  echo "== will mirror to $SCRATCH =="
  printf '%s\n' "$STAGE_LINES" \
    | awk -F'\t' '{printf "  %-22s %s\n      -> %s\n", $2, $3, $4}'
  echo
  # Sizing the source is deliberately skipped: du over a remote tree with 100k+
  # files can itself take minutes, which is the problem we are fixing.
  echo "Local free space under $(dirname "$SCRATCH"):"
  df -h "$(dirname "$SCRATCH")" | tail -1
  echo
fi

if [[ "$DRY_RUN" -eq 1 ]]; then
  echo "Dry run: nothing was copied. Planned work items per tree:"
  while IFS=$'\t' read -r _kind name source dest _env; do
    [[ -n "${name:-}" ]] || continue
    "$PYTHON_BIN" - "$source" "$dest" <<'PY'
import sys
from collections import Counter
from tarsphere.infra.simulation.local_stage import plan_tree_copy

source, destination = sys.argv[1], sys.argv[2]
kinds = Counter(kind for kind, _s, _d in plan_tree_copy(source, destination))
summary = '  '.join(f'{kind}={count}' for kind, count in sorted(kinds.items()))
print(f'  {source}\n    {summary}')
PY
  done <<<"$STAGE_LINES"
  exit 0
fi

if [[ -n "$STAGE_LINES" && "$ASSUME_YES" -eq 0 ]]; then
  read -r -p "Proceed with the copy? [y/N] " reply
  [[ "$reply" == [yY]* ]] || {
    echo "Aborted."
    exit 1
  }
fi

mkdir -p "$SCRATCH"

STAGE_ARGS=(--stage "$SCRATCH")
[[ -n "$WORKERS" ]] && STAGE_ARGS+=(--workers "$WORKERS")
"$PYTHON_BIN" -m tarsphere.infra.simulation.local_stage "${STAGE_ARGS[@]}"
touch "$SCRATCH/.hca-runtime-stage-complete"

RUNTIME_ENV="$SCRATCH/runtime_env.sh"
{
  echo '# Generated by scripts/stage.sh; do not edit.'
  printf 'export TARSPHERE_LOCAL_SCRATCH=%q\n' "$SCRATCH"
  while IFS=$'\t' read -r _kind _name _source destination env_var; do
    [[ -n "${env_var:-}" && "${env_var}" != "-" ]] || continue
    printf 'export %s=%q\n' "$env_var" "$destination"
    if [[ "$env_var" == "TARSPHERE_ASSETS_PATH" ]]; then
      for checkpoint_var in \
        TARSPHERE_XNAVDP_CHECKPOINT TARSPHERE_FRONTIERNET_CHECKPOINT; do
        checkpoint_value="${!checkpoint_var:-}"
        if [[ -n "$checkpoint_value" && "$checkpoint_value" == "${_source}"/* ]]; then
          translated="${destination}/${checkpoint_value#"${_source}"/}"
          printf 'export %s=%q\n' "$checkpoint_var" "$translated"
        fi
      done
    fi
  done <<<"$STAGE_LINES"
  printf 'export XDG_CACHE_HOME=%q\n' "$SCRATCH/cache/xdg"
  printf 'export OMNI_USER_CACHE=%q\n' "$SCRATCH/cache/ov"
} > "$RUNTIME_ENV"

echo
echo "Runtime overrides written to $RUNTIME_ENV."
echo "They are loaded automatically by scripts/activate.sh."
